    <h2 id="about-title">About CampusConnect</h2>
    <p>CampusConnect is a student-led project exploring how an online forum can make academic support feel more accessible. College life can bring academic pressure, social anxiety, and communication barriers that make it hard to ask questions or find help. We want to offer students a welcoming, organized space to learn with one another and build connections across courses and year levels.</p>
    <p>The project is developed by <strong>DigiTols</strong> as part of the Bachelor of Science in Information Technology program at the University of St. La Salle.</p>
  </div>

  <section class="about-section" aria-labelledby="about-goal">
    <h3 id="about-goal">Learning is better together</h3>
    <p>CampusConnect is designed around peer learning: students can ask academic questions, discuss ideas through comments, and exchange study guides, lecture notes, and revision tips. A searchable academic feed can help learners find conversations and resources by course, department, or subject, making it easier to discover relevant help instead of getting lost in unstructured discussions.</p>
    <p>We also recognize that speaking up is not easy for everyone. The project includes optional anonymous question posting as a way to help students seek support with greater confidence and take part at their own pace.</p>
  </section>

  <section class="about-section" aria-labelledby="about-moderation">
    <h3 id="about-moderation">A community cared for by students</h3>
    <p>CampusConnect is intended to be student-led and student-moderated. Its moderator dashboard supports the work of reviewing reported posts, managing queues, and keeping discussions focused, respectful, and useful. Clear moderation roles and tools help student moderators care for the community while students share knowledge and support one another.</p>
    <p>This page is part of the web-based moderator dashboard for the CampusConnect project. The broader project also envisions a mobile experience for students to browse discussions and share academic resources.</p>
  </section>

